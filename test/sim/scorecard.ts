// docs/accuracy-scorecard.md from every test's latest run (test/sim/results/<test>.json): per test and
// criterion the confusion matrix, precision and recall with their one-sided 95% Wilson lower bounds,
// and every wrong case grouped by hazard and parameters.
import type { CaseResult, TestRun } from './types.js';
import { confusion, exactLowerNoErrors, type Confusion } from './stats.js';

const p = (x: number) => `${(100 * x).toFixed(1)}%`;

/** The parameters that differ from case to case, as one short label. */
const label = (r: CaseResult) => Object.entries(r.params).map(([k, v]) => `${k}=${v}`).join(' ');

/** Wrong cases, grouped by (expected → observed, hazard). */
export function wrongGroups(results: readonly CaseResult[]): Map<string, CaseResult[]> {
  const g = new Map<string, CaseResult[]>();
  for (const r of results) {
    if (r.expected.verdict === 'any') continue;
    const wrong = r.expected.verdict === 'fail' ? r.observed !== 'fail' : r.observed === 'fail';
    if (!wrong) continue;
    const kind = r.expected.verdict === 'fail' ? `missed (engine: ${r.observed})` : `false failure (expected ${r.expected.verdict})`;
    const k = `${r.test} ${r.criterion}: ${kind}, hazard ${r.hazard}`;
    g.set(k, [...(g.get(k) ?? []), r]);
  }
  return g;
}

export function accuracyScorecard(runs: readonly TestRun[], notes: Record<string, string> = {}): string {
  const L: string[] = [];
  L.push('# Accuracy scorecard (simulation lab)', '');
  L.push('> Internal. Generated by `pnpm -C packages/engine sim -- --test <id>` (test/sim/). Do not edit by hand.', '');
  L.push('Each case is a generated page whose answer is known by construction (test/sim/tests/*.ts), swept around the');
  L.push('legal threshold and crossed with harness hazards real sites have (smooth scroll, scroll snap, lazy images, late');
  L.push('mounting, a web font swapping in, a cookie banner, a sticky header, prefers-reduced-motion honoured or ignored,');
  L.push('an animation in flight). The engine scans each one with its real probes in real Chromium (scanSite, one page).');
  L.push('');
  L.push('Positive = the page fails the criterion. A failing page the engine passes, finds not applicable or cannot test');
  L.push('counts as missed (FN); a passing page it cannot test is listed (undecided) but is not an error. Lower bounds are');
  L.push('one-sided 95% Wilson; "≥95%?" needs both lower bounds at 0.95 or more. With no errors that takes 52 cases on each');
  L.push('side (the exact binomial bound, shown as "exact", takes 59).', '');
  L.push('| test | criterion | cases | TP | FP | TN | FN | (undecided +/-) | precision | recall | 95% lower bound (precision / recall) | exact, if no errors | ≥95%? | settled pages only (no late mount): lower bounds |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
  const all: Confusion[] = [];
  const settled = new Map<string, Confusion>();
  for (const run of runs) {
    const name = (t: string) => (run.variant ? `${t} @ ${run.variant}` : t);
    for (const c of confusion(run.results)) all.push({ ...c, test: name(c.test) });
    for (const c of confusion(run.results.filter((r) => r.hazard !== 'late-mount'))) settled.set(`${name(c.test)}|${c.criterion}`, c);
  }
  for (const c of all) {
    const exact = c.fp === 0 && c.fn === 0 ? `${p(exactLowerNoErrors(c.tp + c.fp))} / ${p(exactLowerNoErrors(c.tp + c.fn))}` : '';
    L.push(`| ${c.test} | ${c.criterion} | ${c.cases} | ${c.tp} | ${c.fp} | ${c.tn} | ${c.fn} | ${c.undecidedPos} / ${c.undecidedNeg} | ${p(c.precision)} | ${p(c.recall)} | ${p(c.precisionLower)} / ${p(c.recallLower)} | ${exact} | ${c.meets95 ? 'yes' : '**no**'} | ${((s) => (s ? `${p(s.precisionLower)} / ${p(s.recallLower)}${s.meets95 ? ' (≥95%)' : ''}` : ''))(settled.get(`${c.test}|${c.criterion}`))} |`);
  }
  L.push('');
  for (const run of runs) {
    L.push(`## ${run.test}${run.variant ? ` @ ${run.variant}` : ''} (${run.criteria.join(', ')})`, '');
    L.push(`Seed ${run.seed}, ${run.cases} cases, ${Math.round(run.ms / 1000)} s, scoring ${run.engine.scoring}${run.engine.commit ? `, engine ${run.engine.commit}` : ''}, run ${run.startedAt}.`, '');
    if (run.knownIssue) L.push(`Known issue: ${run.knownIssue}`, '');
    if (notes[run.test]) L.push(notes[run.test]!, '');
    // Cases expected 'any' (not counted: AI-review cases, ruled out) are left out of every table here, as from the
    // matrix (Sol round 3); what the engine said on them is listed in its own section below.
    const byHazard = new Map<string, { n: number; wrong: number }>();
    for (const r of run.results) {
      if (r.expected.verdict === 'any') continue;
      const h = byHazard.get(r.hazard) ?? { n: 0, wrong: 0 };
      h.n++;
      if (r.expected.verdict === 'fail' ? r.observed !== 'fail' : r.observed === 'fail') h.wrong++;
      byHazard.set(r.hazard, h);
    }
    L.push('| hazard | cases | wrong |', '|---|---|---|');
    for (const [h, v] of [...byHazard].sort()) L.push(`| ${h} | ${v.n} | ${v.wrong} |`);
    L.push('');
    const notCounted = run.results.filter((r) => r.expected.verdict === 'any');
    if (notCounted.length) {
      const seen = new Map<string, number>();
      for (const r of notCounted) {
        const k = `${r.criterion}: ${String(r.params.kind ?? r.why).slice(0, 60)} → ${r.observed}`;
        seen.set(k, (seen.get(k) ?? 0) + 1);
      }
      L.push(`Not counted (expected "any": AI-review cases and ruled-out cases), ${notCounted.length} results: ${[...seen].map(([k, n]) => `${k} ×${n}`).join('; ')}.`, '');
    }
    const groups = wrongGroups(run.results.filter((r) => r.expected.verdict !== 'any'));
    if (!groups.size) { L.push('No wrong case.', ''); continue; }
    L.push('Wrong cases:', '');
    for (const [k, rs] of groups) {
      L.push(`- **${k}** (${rs.length})`);
      for (const r of rs.slice(0, 12)) L.push(`  - \`${r.id}\` (${label(r)}): ${r.why}. Engine: ${r.details.slice(0, 2).join(' / ').replace(/\|/g, '/').slice(0, 300) || '(no detail)'}`);
      if (rs.length > 12) L.push(`  - … and ${rs.length - 12} more`);
    }
    L.push('');
  }
  L.push('## Not covered yet', '');
  L.push('- AI checks (alt text meaning, 1.1.1 information only in a picture, 1.4.5 pictures of text, the AI forms review): they need');
  L.push('  generated images with known content (rendered text, charts with and without a text equivalent) and recorded model answers');
  L.push('  replayed per case (the gold suite\'s recorded-answer reviewer), plus a second run per case for the two-runs-agree gate.');
  L.push('- Captions and audio description (1.2.x): generated media with and without caption tracks, burned-in captions and described');
  L.push('  tracks (ffmpeg, as the flash video cases), and the platform caption lookups replayed from fixtures.');
  L.push('- Server-side form errors (3.3.1, 3.3.3): out of reach while the forms test sends nothing (see forms).');
  L.push('- Link purpose (2.4.4), ARIA states (4.1.2 beyond form fields), focus visible (2.4.7), bypass blocks (2.4.1), page titles');
  L.push('  (2.4.2), language (3.1.x), consistent navigation and identification (3.2.3, 3.2.4), status messages (4.1.3), on focus and on');
  L.push('  input (3.2.1, 3.2.2): generators not written yet. The deep timing watch (timing-watch) and the AI reviews of focus order,');
  L.push('  headings and labels (2.4.3, 2.4.6) are not run by the second lab report.');
  L.push('');
  return L.join('\n');
}
